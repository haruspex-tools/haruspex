using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;
using Haruspex.Ir;
using Haruspex.SqlServer.Inference;
using Haruspex.Tests.Documentation;
using Kind = Haruspex.Tests.Coverage.SyntaxInventory.ClaimKind;

namespace Haruspex.Tests.Coverage;

/// <summary>
/// Writes <c>docs/coverage.md</c>, what haruspex models: each built-in function the reference documents, against the catalogue
/// and its function table, and each construct of the syntax inventory, with what haruspex says of each. Only
/// <c>CoveragePageTests</c> calls it, to hold the committed page to the code.
/// </summary>
internal static partial class CoveragePage
{
    /// <summary>The page, from the repository's root.</summary>
    public const string Path = "docs/coverage.md";

    private const string InferenceReadme = "../src/Haruspex.SqlServer.Inference/README.md";

    /// <summary>
    /// The page: <paramref name="probed"/> holds the reasons each body of <see cref="FunctionProbes"/> and each example of
    /// the inventory gives, by the body.
    /// </summary>
    public static string Render(DocumentedFunctions functions, SyntaxInventory syntax, IReadOnlyDictionary<string, IReadOnlyList<IrUnknownReason>> probed)
    {
        var page = new StringBuilder();
        page.Append("""
            # What haruspex models

            <!-- Generated by CoveragePageTests. Don't edit this file: tests/coverage/README.md says how to rewrite it. -->

            Every built-in function SQL Server 2025 documents, and every statement, clause, table source, expression and operator its
            parser reads, with what haruspex does with each: how a result is typed and when it may be NULL, or the unknown it gives
            instead. A test writes this page from the code, so it says what haruspex does today and nothing more. The functions come
            from the catalogue of built-in functions, set against the names in Microsoft's reference; the syntax comes from
            ScriptDom's own node types and operators, so nothing is left out by being forgotten; and what haruspex says of each is
            found by running an example of it ([how](../tests/coverage/README.md)). An unknown is never a guess: where haruspex can't
            type something, it claims nothing about it, and the unknown's reason links to what it means and what to do.


            """);
        Summary(page, functions, syntax, probed);
        Functions(page, functions, probed);
        page.Append("## Statements, queries and expressions\n\n");
        page.Append("Each construct as ScriptDom names it. What a modelled construct gives is explained in the section of ")
            .Append($"[the inference's reference]({InferenceReadme}) its claim links.\n\n");
        foreach (var section in syntax.Sections)
            Section(page, section);
        return page.ToString().ReplaceLineEndings("\n").TrimEnd('\n') + "\n";
    }

    private static void Summary(StringBuilder page, DocumentedFunctions functions, SyntaxInventory syntax, IReadOnlyDictionary<string, IReadOnlyList<IrUnknownReason>> probed)
    {
        var names = functions.Names.ToList();
        var modelled = names.Count(n => Rows(n).Any());
        var quiet = names.Where(n => !Rows(n).Any()).Count(n => probed[Probe(n, functions)].Count == 0);
        var entries = syntax.Entries.ToList();
        int Count(params Kind[] kinds) => entries.Count(e => kinds.Contains(e.Claim));

        page.Append("## In numbers\n\n")
            .Append("| What | Count |\n|---|---:|\n")
            .Append(Row("Built-in functions the reference documents", names.Count))
            .Append(Row("In the catalogue", modelled))
            .Append(Row("Not in it, and unknown where they are called", names.Count - modelled - quiet))
            .Append(Row("Not in it, and read without an unknown, as a condition that proves nothing", quiet))
            .Append(Row("Constructs ScriptDom parses", entries.Count))
            .Append(Row("Modelled, wholly or in part", Count(Kind.Modelled, Kind.Partly)))
            .Append(Row("Read, changing no result", Count(Kind.NoEffect)))
            .Append(Row("Unknown", Count(Kind.Unknown, Kind.Unlisted)))
            .Append(Row("Not in a procedure's body, or never parsed from one", Count(Kind.NotInABody, Kind.NotParsed)))
            .Append(Row("Parts of another construct", Count(Kind.Within)))
            .Append('\n');

        static string Row(string what, int count) => $"| {what} | {count.ToString("N0", CultureInfo.InvariantCulture)} |\n";
    }

    private static void Functions(StringBuilder page, DocumentedFunctions functions, IReadOnlyDictionary<string, IReadOnlyList<IrUnknownReason>> probed)
    {
        page.Append("""
            ## Built-in functions

            By the categories of Microsoft's T-SQL reference, read on 15 Nov 2026 (the list, with where it came from:
            [sql-server-2025-functions.txt](../tests/coverage/sql-server-2025-functions.txt)). A function in the catalogue has a row
            for each form it is called in, with its stable code, the type it gives, the reasons it may be NULL besides its
            arguments' ([what each means](../src/Haruspex.SqlServer.Inference/README.md#null-reasons-and-the-constructs-that-give-them)),
            and the tests that observed it on SQL Server. Any other is what haruspex gives for a call of it.


            """);
        foreach (var category in functions.Categories)
        {
            var typed = category.Names.Count(n => Rows(n).Any());
            page.Append($"### {category.Name}\n\n")
                .Append($"{typed.ToString(CultureInfo.InvariantCulture)} of {category.Names.Count.ToString(CultureInfo.InvariantCulture)} in the catalogue. ")
                .Append($"Listed in [the reference]({category.Source}).\n\n")
                .Append(TableHead);
            foreach (var name in category.Names)
            {
                var rows = Rows(name).ToList();
                if (rows.Count == 0)
                {
                    var body = FunctionProbes.For(name, category.Name);
                    page.Append($"| `{name}` | | {NotModelled(probed[body], body)} | | |\n");
                }

                foreach (var row in rows)
                    page.Append(Typed(name, row));
            }

            page.Append('\n');
        }

        var documented = functions.Names.ToHashSet(StringComparer.OrdinalIgnoreCase);
        var others = Typer.FunctionTable.Where(t => !documented.Contains(t.Function.Name)).ToList();
        if (others.Count > 0)
        {
            page.Append("### In the catalogue, not in the reference's list of functions\n\n")
                .Append("Functions the list above doesn't name, such as those the reference documents as expressions; haruspex types them as any other.\n\n")
                .Append(TableHead);
            foreach (var row in others)
                page.Append(Typed(row.Function.Name.ToUpperInvariant(), row));
            page.Append('\n');
        }
    }

    private const string TableHead = "| Function | Code | Gives | NULL besides its arguments | Observed in |\n|---|---|---|---|---|\n";

    private static string Typed(string name, FunctionTyping row)
    {
        var nulls = string.Join(", ", row.MayBeNullBecause.Select(r => $"`{IrWireNames.Of(r)}`"));
        var observed = string.Join(", ", row.ObservedIn.Select(t => $"[{t}](../{Observations.Value[t]})"));
        return $"| `{name}` | `{row.Function.Code}` | {Escape(row.Rule)} | {nulls} | {observed} |\n";
    }

    private static string NotModelled(IReadOnlyList<IrUnknownReason> reasons, string body) => reasons.Count == 0
        ? $"not modelled, and no unknown where it is read as a condition: `{Escape(body)}`"
        : $"not modelled: unknown, {string.Join(", ", reasons.Select(Reason))}";

    private static void Section(StringBuilder page, SyntaxInventory.Section section)
    {
        page.Append($"### {section.Title}\n\n");
        var listed = section.Entries.Where(e => e.Claim != Kind.Unlisted).ToList();
        if (listed.Count > 0)
        {
            page.Append("| Syntax | Node | Claim | What it gives |\n|---|---|---|---|\n");
            foreach (var entry in listed)
                page.Append($"| {Code(entry.Syntax)} | `{entry.Node}` | {Claim(entry)} | {Escape(entry.What)} |\n");
            page.Append('\n');
        }

        var unlisted = section.Entries.Where(e => e.Claim == Kind.Unlisted).Select(e => $"`{e.Node}`").ToList();
        if (unlisted.Count > 0)
        {
            page.Append($"{(listed.Count > 0 ? "And these" : "These")} {unlisted.Count.ToString(CultureInfo.InvariantCulture)} ")
                .Append("statements aren't modelled: each ends what haruspex can list, so the procedure's result sets after it are ")
                .Append($"unknown, {Reason(IrUnknownReason.UnsupportedStatement)}. ")
                .Append(string.Join(", ", unlisted)).Append(".\n\n");
        }
    }

    private static string Claim(SyntaxInventory.Entry entry)
    {
        var modelled = entry.Section is { } section ? $"[modelled]({InferenceReadme}#{MarkdownLinkTests.Slug(section)})" : "modelled";
        return entry.Claim switch
        {
            Kind.Modelled => modelled,
            Kind.NoEffect => "read, changing no result",
            Kind.Unknown => $"unknown, {Reason(Parse(entry.Argument!))}",
            Kind.Partly => $"{modelled} in part; otherwise unknown, {Reason(Parse(entry.Argument!))}",
            Kind.NotInABody => "not in a procedure's body",
            Kind.NotParsed => "never parsed from a body",
            Kind.Within => $"part of `{entry.Argument}`",
            _ => throw new ArgumentOutOfRangeException(nameof(entry), entry.Claim, "Not a claim a table shows."),
        };
    }

    /// <summary>A reason as the IR writes it, linked to its diagnostic's page where it has one.</summary>
    private static string Reason(IrUnknownReason reason) =>
        InferenceCodes.Of(reason) is { } code ? $"[`{IrWireNames.Of(reason)}`](diagnostics/{code}.md)" : $"`{IrWireNames.Of(reason)}`";

    /// <summary>The reason the IR writes as <paramref name="wire"/>.</summary>
    public static IrUnknownReason Parse(string wire) =>
        Enum.GetValues<IrUnknownReason>().Single(r => IrWireNames.Of(r) == wire);

    /// <summary>The rows of the function table for each form of a function of this name; none when the catalogue lacks it.</summary>
    public static IEnumerable<FunctionTyping> Rows(string name) =>
        Typer.FunctionTable.Where(t => t.Function.Name.Equals(name, StringComparison.OrdinalIgnoreCase));

    /// <summary>The probe of a documented function, in the first category that lists it.</summary>
    public static string Probe(string name, DocumentedFunctions functions) =>
        FunctionProbes.For(name, functions.Categories.First(c => c.Names.Contains(name, StringComparer.OrdinalIgnoreCase)).Name);

    private static string Code(string syntax) => syntax.Length == 0 ? "" : $"`{Escape(syntax)}`";

    private static string Escape(string text) => text.Replace("|", @"\|", StringComparison.Ordinal);

    /// <summary>Each observation test's file, from the repository's root, by the test's name.</summary>
    private static readonly Lazy<Dictionary<string, string>> Observations = new(() => Directory
        .EnumerateFiles(System.IO.Path.Combine(RepositoryPaths.Root, "tests", "Haruspex.DifferentialTests"), "*.cs", SearchOption.AllDirectories)
        .SelectMany(f => TestMethod().Matches(File.ReadAllText(f)).Select(m => (Name: m.Groups["name"].Value, File: f)))
        .GroupBy(m => m.Name, StringComparer.Ordinal)
        .ToDictionary(g => g.Key, g => System.IO.Path.GetRelativePath(RepositoryPaths.Root, g.First().File).Replace('\\', '/'), StringComparer.Ordinal));

    [GeneratedRegex(@"public (?:async Task|void) (?<name>\w+)\(")]
    private static partial Regex TestMethod();
}
