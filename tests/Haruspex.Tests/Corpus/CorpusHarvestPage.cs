using System.Globalization;
using System.Text;
using Haruspex.Diagnostics;
using Haruspex.Ir;
using static Haruspex.Tests.Corpus.CorpusFiguresPage;

namespace Haruspex.Tests.Corpus;

/// <summary>
/// Writes <c>docs/corpus-harvest.md</c>: the harvest across every corpus, then the figures of each fetched corpus. The page holds
/// counts only. A fetched corpus's code may be under a licence the repository's isn't, copyleft included, so no name, IR or
/// Zod derived from it is written here, not even the name of a file it leaves out (the manifest lists those).
/// </summary>
internal static class CorpusHarvestPage
{
    /// <summary>The page, relative to the repository's root.</summary>
    public const string Path = "docs/corpus-harvest.md";

    /// <summary>The page for these runs: the vendored corpora's, for the harvest, and every fetched corpus's.</summary>
    public static string Render(IReadOnlyList<CorpusRun> vendored, IReadOnlyList<FetchedCorpusRun> fetched)
    {
        ArgumentNullException.ThrowIfNull(vendored);
        ArgumentNullException.ThrowIfNull(fetched);
        var all = vendored.Select(r => CorpusFigures.Count(r.Document)).Concat(fetched.Select(r => r.Figures)).ToList();
        var page = new StringBuilder();
        page.Append(CultureInfo.InvariantCulture, $"""
            # The harvest: what public corpora show haruspex missing

            <!-- Generated by CorpusHarvestTests. Don't edit this file: tests/corpus/README.md says how to rewrite it. -->

            What haruspex can't yet type in {N(all.Count)} public corpora, ranked, and how much of each it types. A test writes this
            page from the corpora, so a figure here is always what the code does
            ([decision 0020](decisions/0020-public-figures-come-from-public-corpora.md)). Two of the corpora are Microsoft's samples
            vendored in the repository, whose own figures are on [the corpus figures](corpus-figures.md); the others are fetched at
            a pinned commit into a folder outside the checkout, never committed ([how and why](../tests/corpus/README.md)). From a
            fetched corpus this page keeps counts only: no name, IR or generated code. Every procedure in every schema is inferred,
            with no config file, into IR version {IrDocument.OneDatabaseVersion}, and counted as
            [the corpus figures define](corpus-figures.md#how-the-figures-are-counted).

            ## The harvest

            Every reason something is unknown, summed over the corpora, most first: each row is a gap in what haruspex models, and
            the rows at the top are where work types the most. **Places** adds the four columns before it.


            """);
        page.Append("| Reason | Fields | Results of unknown shape | Procedures whose result sets can't be listed | Parameters | Places | Corpora |\n|---|---:|---:|---:|---:|---:|---:|\n");
        foreach (var row in CorpusHarvest.Unknowns(all))
            page.Append(CultureInfo.InvariantCulture, $"| `{row.Name}` | {N(row.Fields)} | {N(row.Results)} | {N(row.Procedures)} | {N(row.Parameters)} | {N(row.Total)} | {N(row.Corpora)} |\n");

        page.Append("""

            ### Diagnostics by code

            What reading the corpora reported, most often first. An error leaves a script, or the objects in it, out of what is read.


            """);
        var codes = CorpusHarvest.Diagnostics([.. vendored.Select(r => r.Errors), .. fetched.Select(r => r.Diagnostics)]);
        Codes(page, [.. codes.Select(r => (r.Code, r.Count, (int?)r.Corpora))]);

        page.Append("""

            ## Coverage

            Corpora written as applications' databases: how much of each haruspex types.

            """);
        foreach (var run in fetched.Where(r => r.Corpus.Kind == FetchedCorpusKind.Coverage))
            Coverage(page, run);

        page.Append("""

            ## Tools

            Corpora written as tools, for administering a server or testing code in it, not as an application's database. They are
            heavy on dynamic SQL and system views, so few of their procedures return a shape that can be known before they run:
            what they measure is whether haruspex reads them, and whether what it can't type is unknown for a reason that fits,
            not how much it types.

            """);
        foreach (var run in fetched.Where(r => r.Corpus.Kind == FetchedCorpusKind.Tool))
            Tool(page, run);

        return page.ToString().ReplaceLineEndings("\n");
    }

    private static void Coverage(StringBuilder page, FetchedCorpusRun run)
    {
        var f = run.Figures;
        page.Append(CultureInfo.InvariantCulture, $"""

            ### {run.Corpus.Name}

            {Summary(run.Corpus.Name, f)}

            {Source(run.Corpus)}

            | Figure | Count |
            |---|---:|
            {ReadRows(run)}

            """);
        page.Append(FigureRows(f));
        page.Append("\n#### Unknowns by reason\n\n");
        UnknownsByReason(page, f);
        Details(page, run);
    }

    private static void Tool(StringBuilder page, FetchedCorpusRun run)
    {
        var f = run.Figures;
        page.Append(CultureInfo.InvariantCulture, $"""

            ### {run.Corpus.Name}

            {Source(run.Corpus)}

            | Figure | Count |
            |---|---:|
            {ReadRows(run)}
            | Procedures | {N(f.Procedures)} |
            | Procedures whose result sets can be listed | {N(f.Procedures - f.ProceduresWithUnlistedResults)} |
            | Procedures whose result sets can't be listed | {N(f.ProceduresWithUnlistedResults)} |

            """);
        page.Append("\n#### Unknowns by reason\n\n");
        UnknownsByReason(page, f);
        Details(page, run);
    }

    /// <summary>Where the corpus comes from, under which licence, and what it is.</summary>
    private static string Source(FetchedCorpus corpus)
    {
        var notices = corpus.Licence.Notices.Count == 0
            ? ""
            : $" and {string.Join(" and ", corpus.Licence.Notices.Select(n => $"`{n}`"))}";
        return string.Create(CultureInfo.InvariantCulture, $"""
            From [its repository]({corpus.Repository}) at commit `{corpus.Commit}`, under `{corpus.Licence.Spdx}` (`{corpus.Licence.File}`{notices}, fetched with it). {corpus.About}
            """);
    }

    /// <summary>The rows that count scripts and what reading them reported, one per line, with no line break after the last.</summary>
    private static string ReadRows(FetchedCorpusRun run)
    {
        var errors = run.Diagnostics.Count(d => d.IsError);
        return string.Create(CultureInfo.InvariantCulture, $"""
            | Scripts fetched | {N(run.Corpus.Scripts.Count())} |
            | Scripts left out | {N(run.Corpus.LeftOut.Sum(o => o.Files.Count))} |
            | Errors reading them | {N(errors)} |
            | Warnings reading them | {N(run.Diagnostics.Count - errors)} |
            """);
    }

    /// <summary>Diagnostics by code, and the groups of scripts left out with their reasons: never a name from the corpus.</summary>
    private static void Details(StringBuilder page, FetchedCorpusRun run)
    {
        if (run.Diagnostics.Count > 0)
        {
            page.Append("\n#### Diagnostics by code\n\n");
            Codes(page, [.. CorpusHarvest.Diagnostics([run.Diagnostics]).Select(r => (r.Code, r.Count, (int?)null))]);
        }

        if (run.Corpus.LeftOut.Count > 0)
        {
            page.Append("\n#### Scripts left out\n\nThe manifest names each.\n\n");
            foreach (var group in run.Corpus.LeftOut)
                page.Append(CultureInfo.InvariantCulture, $"- {Count(group.Files.Count, "script")}: {group.Why}\n");
        }
    }

    private static void Codes(StringBuilder page, List<(DiagnosticCode Code, int Count, int? Corpora)> rows)
    {
        if (rows.Count == 0)
        {
            page.Append("Nothing was reported.\n");
            return;
        }

        var withCorpora = rows[0].Corpora is not null;
        page.Append(withCorpora ? "| Code | What | Severity | Reported | Corpora |\n|---|---|---|---:|---:|\n" : "| Code | What | Severity | Reported |\n|---|---|---|---:|\n");
        foreach (var (code, count, corpora) in rows)
        {
            var severity = code.Severity.ToString().ToLowerInvariant();
            page.Append(CultureInfo.InvariantCulture, $"| [{code}](diagnostics/{code}.md) | {code.Title} | {severity} | {N(count)} |");
            page.Append(withCorpora ? string.Create(CultureInfo.InvariantCulture, $" {N(corpora ?? 0)} |\n") : "\n");
        }
    }
}
