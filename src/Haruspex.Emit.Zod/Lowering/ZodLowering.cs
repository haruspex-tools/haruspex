using System.Globalization;
using Haruspex.Emit.Zod.Model;
using Haruspex.Emit.Zod.Planning;
using Haruspex.Ir;
using static Haruspex.Emit.Zod.Model.ZodExpression;

namespace Haruspex.Emit.Zod.Lowering;

/// <summary>
/// The second stage: the plan's every entry as a declaration, built from Zod expressions (<see cref="ZodModule"/>). What
/// each IR type becomes is <see cref="TypeLowering"/>'s; this decides what a procedure's results and a named object type
/// become, and what the reader of the module is told about them.
/// </summary>
internal static class ZodLowering
{
    /// <summary>The module the plan describes.</summary>
    public static ZodModule Lower(ZodPlan plan)
    {
        ArgumentNullException.ThrowIfNull(plan);
        var declaredAs = SameShapes(plan);
        var types = new TypeLowering(plan.Document.Types, name => declaredAs[name]);
        List<ZodDeclaration> declarations =
        [
            .. plan.Entries.Select(entry => entry switch
            {
                ZodPlanEntry.NamedType named when declaredAs[named.Name] != named.Name => Alias(named.Name, declaredAs[named.Name]),
                ZodPlanEntry.NamedType named => ObjectType(named, plan, types),
                ZodPlanEntry.Procedure procedure => Procedure(procedure.Object, types),
            }),
        ];
        return new ZodModule([.. Header(plan.Document.Source, declarations)], plan.Imports, plan.UsesJsonText, [.. declarations], plan.Document.Folds);
    }

    /// <summary>
    /// The header: what made the module, what the callers' sessions were declared to set, and once each, the shared facts its
    /// properties' notes rest on (<see cref="ZodCaveat"/>), so that a note can say what is particular to its property in one
    /// sentence.
    /// </summary>
    private static IEnumerable<string> Header(IrSource source, IEnumerable<ZodDeclaration> declarations)
    {
        yield return $"Generated by haruspex from IR {IrDocument.CurrentVersion}. Do not edit.";
        yield return "Rowset results follow the default type mapping of the mssql (tedious) driver.";

        // A schema is only as true as what it assumed, so a declared session is said where the schema is read; with none
        // declared nothing is assumed, and nothing is said.
        if (source.Session.Count > 0)
        {
            var options = source.Session.Select(o => $"{o.Name} {(o.On ? "on" : "off")}");
            yield return $"Its types assume that callers' sessions set {Listed([.. options])}, as the config file declares.";
        }

        var caveats = declarations.Select(d => d.Schema).OfType<ObjectSchema>()
            .SelectMany(o => o.Properties).Select(p => p.Value)
            .Concat(declarations.Select(d => d.Schema)).SelectMany(ZodNotes.Of).Select(n => n.Caveat).OfType<ZodCaveat>()
            .Distinct().Order().ToList();
        if (caveats.Count == 0)
            yield break;
        yield return "";
        yield return "The notes on properties below rest on these facts:";
        foreach (var caveat in caveats)
            yield return "- " + Caveat(caveat);
    }

    /// <summary>Items as an English list: <c>a</c>, <c>a and b</c>, <c>a, b and c</c>.</summary>
    private static string Listed(IReadOnlyList<string> items) =>
        items.Count == 1 ? items[0] : string.Join(", ", items.Take(items.Count - 1)) + " and " + items[^1];

    private static string Caveat(ZodCaveat caveat) => caveat switch
    {
        ZodCaveat.ByteLengths =>
            "varchar(n) and char(n) count bytes, not characters. A character is one byte only in a single-byte collation, so " +
            "elsewhere n bounds the length from above.",
        ZodCaveat.CollationValueSets =>
            "A value set from a CHECK constraint holds as the database compares strings, where case, accents and trailing " +
            "spaces may differ, so it is a note rather than z.enum.",
        ZodCaveat.DriverDecimals =>
            "The mssql driver builds a decimal or money of more than 15 digits as a double, which may land just past the type's bounds.",
        ZodCaveat.Doubles =>
            "JavaScript reads every number, in JSON or in this file, as a double, which holds every integer up to 2^53 exactly, " +
            "and keeps the digits of any decimal of up to 15 significant digits.",
        _ => throw new ArgumentOutOfRangeException(nameof(caveat), caveat, "A caveat outside the closed set."),
    };

    /// <summary>
    /// The name each named type is declared under: its own, or that of the first type in the plan with the same schema.
    /// Identical shapes are declared once, as the design asks; the others' names stay, as aliases, so code that imports
    /// one keeps working (<see cref="Alias"/>).
    /// </summary>
    /// <remarks>
    /// Two schemas are the same when their models are equal, notes included, which records give by value. A schema
    /// refers to others by name, so merging two leaf types can make their users the same too: the comparison is repeated
    /// with the names merged so far until nothing more merges. Merges only ever add, so it ends. Two recursive types are
    /// never found the same, since each refers to itself by its own name, which only claims less.
    /// </remarks>
    private static Dictionary<string, string> SameShapes(ZodPlan plan)
    {
        var named = plan.Entries.OfType<ZodPlanEntry.NamedType>().ToList();
        var declaredAs = named.ToDictionary(n => n.Name, n => n.Name, StringComparer.Ordinal);
        while (true)
        {
            var types = new TypeLowering(plan.Document.Types, name => declaredAs[name]);
            var first = new Dictionary<ZodExpression, string>();
            var next = new Dictionary<string, string>(StringComparer.Ordinal);
            foreach (var type in named)
            {
                var schema = ObjectType(type, plan, types).Schema;
                next[type.Name] = first.TryGetValue(schema, out var earlier) ? earlier : first[schema] = type.Name;
            }

            if (next.All(n => declaredAs[n.Key] == n.Value))
                return declaredAs;
            declaredAs = next;
        }
    }

    /// <summary>A named type of the same shape as one declared earlier: its name, kept for importers, for that schema.</summary>
    private static ZodDeclaration Alias(string name, string declaredAs) =>
        new(name, $"The same shape as {declaredAs}.", new Name(ZodModule.SchemaOf(declaredAs)));

    /// <summary>
    /// A named object type: an object schema with a property per field. Strip by default: unknown keys are dropped at parse
    /// time, so a column the database adds before the application redeploys doesn't break it. Strict is a setting for
    /// projects that deploy the application first or together, and want an unexpected key to fail
    /// (<c>docs/decisions/0008-objects-strip-unknown-keys-by-default.md</c>). Every object here is part of a result.
    /// </summary>
    private static ZodDeclaration ObjectType(ZodPlanEntry.NamedType named, ZodPlan plan, TypeLowering types)
    {
        // A field that refers back into its own cycle (a tree's children) is a getter, Zod 4's form for recursive objects:
        // the schema it names may not be declared yet, and TypeScript infers the type through a getter without casts. Every
        // such reference is one, whichever type of the cycle is declared first.
        var properties = named.Type.Fields.Select(field => new ZodProperty(
            field.Name,
            types.Field(field, named.Encoding),
            Getter: IrTypeTree.References(field.Type).Any(reference => plan.Graph.OnOneCycle(named.Name, reference))));
        return new ZodDeclaration(named.Name, null, new ObjectSchema([.. properties], plan.Options.Objects == ZodObjects.Strict));
    }

    /// <summary>A procedure: its one result's schema, a tuple of several, or <c>z.unknown()</c> when they can't be listed.</summary>
    private static ZodDeclaration Procedure(IrObject obj, TypeLowering types)
    {
        var summary = obj.Results switch
        {
            null => "its result sets cannot be listed; see the unknowns in the IR",
            [] => "returns no result sets",
            [var single] => $"returns {Describe(single)}",
            var many => $"returns {many.Count} result sets: " + string.Join("; ", many.Select(Describe)),
        };
        var schema = obj.Results switch
        {
            null => Z("unknown"),
            [var single] => Result(single, types),
            var many => Z("tuple", new ArrayLiteral([.. many.Select(r => Result(r, types))])),
        };
        return new ZodDeclaration(obj.Name, $"{obj.Id}: {summary}.", schema);
    }

    /// <summary>
    /// A result's schema. A result that may be absent follows the reader convention in the IR's README: a rowset reads as
    /// <c>[]</c>, so its schema is unchanged, and a JSON result reads as <c>null</c>, whatever its type, because that is
    /// what the mssql driver hands over for a FOR JSON query that matched no rows
    /// (<c>docs/decisions/0048-an-absent-json-result-reads-as-null.md</c>).
    /// </summary>
    private static ZodExpression Result(IrResult result, TypeLowering types)
    {
        var schema = result.Type is IrArray array ? Rows(array, result, types) : types.Type(result.Type, result.Encoding);

        // A rowset reads as no rows when absent, whatever its type (a union of arrays when branches return different rows).
        // An unknown JSON result already accepts null.
        return result.MayBeAbsent && result.Encoding == IrEncoding.Json && result.Type is not IrUnknownType
            ? schema.Then("nullable")
            : schema;
    }

    /// <summary>
    /// A result of rows, a rowset or FOR JSON's array, bounded by its cardinality: it has no more rows than that, and exactly
    /// one when it is one and arrives. An absent rowset reads as [], so one that may be absent is only bounded above. FOR
    /// JSON over no rows returns no row at all, which reads as null, so a JSON array that arrives has an item for each of at
    /// least one row. Each bound is written once, the tighter of the cardinality's and the array's own (a declared result's
    /// <c>minItems</c>, say). A union of arrays is not bounded, which only claims less.
    /// </summary>
    private static ZodExpression Rows(IrArray array, IrResult result, TypeLowering types)
    {
        var json = result.Encoding == IrEncoding.Json;
        int? fewest = json || (result.Cardinality == IrCardinality.One && !result.MayBeAbsent) ? 1 : null;
        int? most = result.Cardinality is IrCardinality.One or IrCardinality.AtMostOne ? 1 : null;
        var min = array.MinItems is { } ownMin && fewest is { } least ? Math.Max(ownMin, least) : array.MinItems ?? fewest;
        var max = array.MaxItems is { } ownMax && most is { } greatest ? Math.Min(ownMax, greatest) : array.MaxItems ?? most;

        var schema = types.Type(array with { MinItems = null, MaxItems = null }, result.Encoding);
        if (min is { } exactly && max == exactly)
            return schema.Then("length", Count(exactly));
        if (min is { } low)
            schema = schema.Then("min", Count(low));
        return max is { } high ? schema.Then("max", Count(high)) : schema;
    }

    private static Number Count(int count) => new(count.ToString(CultureInfo.InvariantCulture));

    /// <summary>
    /// What a result is, and what it reads as when absent: a FOR JSON query that matched no rows, or a statement that did not
    /// run (in a branch, or after a RETURN), whose result set is then missing altogether.
    /// </summary>
    private static string Describe(IrResult result)
    {
        var noRows = result.AbsentBecause.Any(r => r.Rule == IrNullRule.NoRows);
        var notRun = result.AbsentBecause.Any(r => r.Rule == IrNullRule.NotRun);
        var when = (noRows, notRun) switch
        {
            (true, true) => "when no rows match or it does not run",
            (true, false) => "when no rows match",
            (false, true) => "when it does not run",
            _ => null,
        };
        var what = result.Encoding == IrEncoding.Rowset ? "rows" : "JSON";
        return when is null ? what : $"{what}, {(result.Encoding == IrEncoding.Rowset ? "[]" : "null")} {when}";
    }
}
