using System.Collections.Frozen;
using System.Globalization;
using Haruspex.Collections;
using Haruspex.Emit.Zod.Model;
using Haruspex.Emit.Zod.Planning;
using Haruspex.Emit.Zod.Printing;
using Haruspex.Ir;
using static Haruspex.Emit.Zod.Model.ZodExpression;

namespace Haruspex.Emit.Zod.Lowering;

/// <summary>
/// The second stage: the plan's every entry as a declaration, built from Zod expressions (<see cref="ZodModule"/>). What
/// each IR type becomes is <see cref="TypeLowering"/>'s, and what a procedure's parameters become
/// <see cref="ParameterLowering"/>'s; this decides what a procedure's results and a named object type become, and what the
/// reader of the module is told about them.
/// </summary>
internal static class ZodLowering
{
    /// <summary>The module the plan describes.</summary>
    public static ZodModule Lower(ZodPlan plan)
    {
        ArgumentNullException.ThrowIfNull(plan);
        var placed = Placed(plan);
        List<ZodDeclaration> declarations = [.. placed.Select(p => p.Declaration)];
        var header = Header(plan.Document.Source, plan.Document.Version, declarations, LeavesOutNullKeys(plan.Document, placed.SelectMany(p => p.Types)));
        return new ZodModule([.. header], plan.Imports, plan.UsesJsonText, [.. declarations], plan.Document.Folds);
    }

    /// <summary>
    /// The plan's every entry as declarations, in the module's order, each with what it rests on, which decides the file it goes
    /// in when the module is split (<see cref="ZodSplit"/>).
    /// </summary>
    internal static IReadOnlyList<PlacedDeclaration> Placed(ZodPlan plan)
    {
        ArgumentNullException.ThrowIfNull(plan);
        var shapes = SharedShapes(plan);

        // A reference names its type's own exported schema, which reads as what it is; only inside a shared shape does it name
        // the shapes it holds by their bindings, so that the shape is the same whichever of its types it was built from.
        var types = new TypeLowering(plan.Document.Types, ZodModule.SchemaOf);
        var shared = new TypeLowering(plan.Document.Types, name => shapes.SchemaOf[name]);
        var hosted = new HashSet<string>(StringComparer.Ordinal);
        return
        [
            .. plan.Entries.SelectMany(entry => entry switch
            {
                ZodPlanEntry.NamedType named => Named(named, plan, types, shared, shapes, hosted),
                ZodPlanEntry.TableRow row => [new PlacedDeclaration(ParameterLowering.TableRow(row.Name, row.Type, types), null, [row.Name])],

                // What a caller sends, then what comes back: the results, and the OUTPUT parameters.
                ZodPlanEntry.Procedure procedure => new[]
                {
                    ParameterLowering.Declaration(procedure.Object, types),
                    Procedure(procedure.Object, types),
                    ParameterLowering.OutputDeclaration(procedure.Object, types),
                }.OfType<ZodDeclaration>().Select(d => new PlacedDeclaration(d, procedure.Object, [])),
            }),
        ];
    }

    /// <summary>
    /// Whether any of the named types has a key <c>FOR JSON</c> may leave out because its value is null, which the header then
    /// says once.
    /// </summary>
    internal static bool LeavesOutNullKeys(IrDocument document, IEnumerable<string> types) =>
        types.Any(name => document.Types.TryGetValue(name, out var type)
            && type.Fields.Any(f => f.Presence == IrPresence.OmittedWhenNull && f.Nullable));

    /// <summary>
    /// The header: what made the module, what the callers' sessions were declared to set, that <c>FOR JSON</c> leaves out a null
    /// key when the module has such a key, and once each, the shared facts its properties' notes rest on (<see cref="ZodCaveat"/>),
    /// so that a note can say what is particular to its property in one sentence.
    /// </summary>
    /// <remarks>
    /// The rule for null keys is said here rather than on each key, so that a key left out only because its column is nullable
    /// needs no comment of its own (<see cref="IrSurprises"/>; <c>docs/decisions/0079-a-surprise-is-explained-where-it-is-written.md</c>).
    /// </remarks>
    internal static IEnumerable<string> Header(IrSource source, string version, IEnumerable<ZodDeclaration> declarations, bool leavesOutNullKeys)
    {
        yield return $"Generated by haruspex from IR {version}. Do not edit.";
        yield return "Rowset results follow the default type mapping of the mssql (tedious) driver.";
        if (IrSourceText.Baseline(source) is { } combined)
            yield return combined;

        // A schema is only as true as what it assumed, so a declared session is said where the schema is read; with none
        // declared nothing is assumed, and nothing is said.
        if (source.Session.Count > 0)
        {
            var options = source.Session.Select(o => $"{o.Name} {(o.On ? "on" : "off")}");
            yield return $"Its types assume that callers' sessions set {Listed([.. options])}, as the config file declares.";
        }

        if (leavesOutNullKeys)
            yield return IrFieldText.KeyLeftOutWhenNull + ", so a key they may leave out is optional rather than nullable.";

        var caveats = declarations.Select(d => d.Schema).OfType<ObjectSchema>()
            .SelectMany(o => o.Properties).Select(p => p.Value)
            .Concat(declarations.Select(d => d.Schema)).SelectMany(ZodNotes.Of).Select(n => n.Caveat).OfType<ZodCaveat>()
            .Distinct().Order().ToList();
        if (caveats.Count == 0)
            yield break;
        yield return "";
        yield return "The notes on properties below rest on these facts:";
        foreach (var caveat in caveats)
            yield return "- " + Caveat(caveat);
    }

    /// <summary>Items as an English list: <c>a</c>, <c>a and b</c>, <c>a, b and c</c>.</summary>
    private static string Listed(IReadOnlyList<string> items) =>
        items.Count == 1 ? items[0] : string.Join(", ", items.Take(items.Count - 1)) + " and " + items[^1];

    private static string Caveat(ZodCaveat caveat) => caveat switch
    {
        ZodCaveat.ByteLengths =>
            "varchar(n) and char(n) count bytes, not characters. A character is one byte only in a single-byte collation, so " +
            "elsewhere n bounds the length from above.",
        ZodCaveat.CodePoints =>
            $"Zod {ZodEmitter.LeastZod} and later count a string's length in code points (earlier releases may count UTF-16 code " +
            "units), and SQL Server in UTF-16 code units or bytes, of which a code point may take more than one, so a fixed or " +
            "least length holds fewer code points than it counts.",
        ZodCaveat.CollationValueSets =>
            "A value set from a CHECK constraint holds as the database compares strings, where case, accents and trailing " +
            "spaces may differ, so it is a note rather than z.enum.",
        ZodCaveat.DriverDecimals =>
            "The mssql driver builds a decimal or money of more than 15 digits as a double, which may land just past the type's bounds.",
        ZodCaveat.Doubles =>
            "JavaScript reads every number, in JSON or in this file, as a double, which holds every integer up to 2^53 exactly, " +
            "and keeps the digits of any decimal of up to 15 significant digits.",
        _ => throw new ArgumentOutOfRangeException(nameof(caveat), caveat, "A caveat outside the closed set."),
    };

    /// <summary>
    /// A named type's declarations. A type whose shape no other shares is declared as itself. One that shares its shape is exported
    /// under its own name as the shared schema, which is declared once, where the first of the types that share it is: under the
    /// name the config file gave one of them, or else unexported under a name made from its structure (<see cref="ShapeNames"/>).
    /// So every exported name is its own type's, and none depends on which procedure came first
    /// (<c>docs/decisions/0071-a-shared-shape-is-named-by-declaration-or-by-its-structure.md</c>).
    /// </summary>
    private static IEnumerable<PlacedDeclaration> Named(ZodPlanEntry.NamedType named, ZodPlan plan, TypeLowering types, TypeLowering shared, SharedShapeNames shapes, HashSet<string> hosted)
    {
        if (!shapes.Host.TryGetValue(named.Name, out var host))
        {
            yield return new PlacedDeclaration(ObjectType(named, plan, types, explained: true), null, [named.Name]);
            yield break;
        }

        // The shared schema is built from this type, the first of those sharing it, so it is declared before every alias. It
        // rests on every type that shares it, so a split module puts it where all of them are.
        if (hosted.Add(host.Binding))
        {
            // Without explanations, which differ between the types that share it: each says its own above its export.
            var schema = ObjectType(named, plan, shared, explained: false).Schema;
            var declaration = host.Declared is { } declared
                ? new ZodDeclaration(declared, SharedSummary, schema) { Explanation = Explanation(plan.Document.Types[declared], declared, plan) }
                : new ZodDeclaration(host.Binding, SharedSummary, schema, Exported: false);
            yield return new PlacedDeclaration(declaration, null, host.Members);
        }

        if (host.Declared != named.Name)
            yield return new PlacedDeclaration(new ZodDeclaration(named.Name, null, new Name(host.Binding)) { Explanation = Explanation(named.Type, named.Name, plan) }, null, [named.Name]);
    }

    /// <summary>What the reader of the module is told of a shape declared once for several types.</summary>
    private const string SharedSummary = "A shape several types share, declared once; each is exported under its own name.";

    /// <summary>
    /// Where each named type's schema is bound (<see cref="SharedShapeNames"/>). Types of the same shape are found first: two
    /// schemas are the same when their models are equal, notes included, which records give by value. A schema refers to others
    /// by name, so merging two leaf types can make their users the same too: the comparison is repeated with the names merged so
    /// far until nothing more merges. Merges only ever add, so it ends. Two recursive types are never found the same, since each
    /// refers to itself by its own name, which only claims less.
    /// </summary>
    /// <remarks>
    /// Then each group of more than one type is given its binding, in the plan's order, which puts a type after the types it
    /// refers to, so a shape is named after the shapes inside it are: by a name the config file declared for one of its types, the
    /// ordinally first when several were, and otherwise by its schema's text, in which a shape inside it appears by its own name.
    /// </remarks>
    private static SharedShapeNames SharedShapes(ZodPlan plan)
    {
        var named = plan.Entries.OfType<ZodPlanEntry.NamedType>().ToList();
        var sameAs = named.ToDictionary(n => n.Name, n => n.Name, StringComparer.Ordinal);
        while (true)
        {
            var lowering = new TypeLowering(plan.Document.Types, name => ZodModule.SchemaOf(sameAs[name]));
            var first = new Dictionary<ZodExpression, string>();
            var next = new Dictionary<string, string>(StringComparer.Ordinal);
            foreach (var type in named)
            {
                var schema = ObjectType(type, plan, lowering, explained: false).Schema;
                next[type.Name] = first.TryGetValue(schema, out var earlier) ? earlier : first[schema] = type.Name;
            }

            if (next.All(n => sameAs[n.Key] == n.Value))
                break;
            sameAs = next;
        }

        var groups = named.GroupBy(n => sameAs[n.Name], StringComparer.Ordinal).Where(g => g.Count() > 1).ToList();
        var schemaOf = named.ToDictionary(n => n.Name, n => ZodModule.SchemaOf(n.Name), StringComparer.Ordinal);
        var host = new Dictionary<string, SharedShape>(StringComparer.Ordinal);
        var shapeNames = new ShapeNames(plan.Imports.SelectMany(i => i.Names));
        var types = new TypeLowering(plan.Document.Types, name => schemaOf[name]);
        foreach (var group in groups)
        {
            var declared = group.Where(t => t.Type.NameDeclared).Select(t => t.Name).Order(StringComparer.Ordinal).FirstOrDefault();
            EquatableArray<string> members = [.. group.Select(t => t.Name)];
            var shape = declared is not null
                ? new SharedShape(ZodModule.SchemaOf(declared), declared, members)
                : new SharedShape(shapeNames.Of(ZodPrinter.Expression(ObjectType(group.First(), plan, types, explained: false).Schema)), null, members);
            foreach (var type in group)
            {
                schemaOf[type.Name] = shape.Binding;
                host[type.Name] = shape;
            }
        }

        return new SharedShapeNames(schemaOf, host);
    }

    /// <summary>Where each named type's schema is bound, and for a type that shares its shape, where the shared schema is.</summary>
    /// <param name="schemaOf">The binding each named type's schema is: its own schema's, or its shared shape's.</param>
    /// <param name="host">For each type that shares its shape with another, the shape.</param>
    private sealed class SharedShapeNames(Dictionary<string, string> schemaOf, Dictionary<string, SharedShape> host)
    {
        /// <summary>The binding each named type's schema is: its own schema's, or its shared shape's.</summary>
        public FrozenDictionary<string, string> SchemaOf { get; } = schemaOf.ToFrozenDictionary(StringComparer.Ordinal);

        /// <summary>For each type that shares its shape with another, the shape.</summary>
        public FrozenDictionary<string, SharedShape> Host { get; } = host.ToFrozenDictionary(StringComparer.Ordinal);
    }

    /// <summary>A shape several types share, declared once.</summary>
    /// <param name="Binding">The binding its schema is declared under: <c>OrderTotalSchema</c>, or <c>shape3f2a9c</c>.</param>
    /// <param name="Declared">The type whose declared name it is exported under, or null when it is not exported.</param>
    /// <param name="Members">The types that share it, in the plan's order.</param>
    private sealed record SharedShape(string Binding, string? Declared, EquatableArray<string> Members);

    /// <summary>
    /// A named object type: an object schema with a property per field. Strip by default: unknown keys are dropped at parse
    /// time, so a column the database adds before the application redeploys doesn't break it. Strict is a setting for
    /// projects that deploy the application first or together, and want an unexpected key to fail
    /// (<c>docs/decisions/0008-objects-strip-unknown-keys-by-default.md</c>). An open object, of JSON a column is declared to
    /// hold, is loose whatever the setting: whoever wrote it may have added keys it doesn't list, which are part of its value, so
    /// they are kept rather than refused or dropped. Every object here is part of a result.
    /// </summary>
    /// <param name="named">The type.</param>
    /// <param name="plan">The module's plan.</param>
    /// <param name="types">How a type is lowered, and its references bound.</param>
    /// <param name="explained">
    /// Whether each property says why its field is what it is: not for a shape several types share, which is compared and declared
    /// without them, so that comments never stop a shape being shared.
    /// </param>
    private static ZodDeclaration ObjectType(ZodPlanEntry.NamedType named, ZodPlan plan, TypeLowering types, bool explained)
    {
        // A field that refers back into its own cycle (a tree's children) is a getter, Zod 4's form for recursive objects:
        // the schema it names may not be declared yet, and TypeScript infers the type through a getter without casts. Every
        // such reference is one, whichever type of the cycle is declared first.
        var properties = named.Type.Fields.Select(field => new ZodProperty(
            field.Name,
            types.Field(field, named.Encoding).Described(field.Description),
            Getter: IrTypeTree.References(field.Type).Any(reference => plan.Graph.OnOneCycle(named.Name, reference)))
        {
            Explanation = explained ? [.. IrFieldText.Of(plan.Document, named.Name, field, plan.Options.Comments)] : [],
            Description = field.Description,
        });
        return new ZodDeclaration(named.Name, null, new ObjectSchema([.. properties], plan.Options.Objects == ZodObjects.Strict && !named.Type.Open) { Loose = named.Type.Open });
    }

    /// <summary>
    /// Why each field of a type that shares its shape is what it is, a line each, the field's name first, for the comment above
    /// its export.
    /// </summary>
    private static EquatableArray<string> Explanation(IrObjectType type, string name, ZodPlan plan) =>
    [
        .. type.Fields.SelectMany(field => IrFieldText.Of(plan.Document, name, field, plan.Options.Comments).Select(line => $"{field.Name}: {line}")),
    ];

    /// <summary>
    /// A procedure: an object of its result sets by name when they are named, even one
    /// (<c>docs/decisions/0070-a-procedure-s-result-sets-are-named-all-or-none.md</c>); otherwise its one result's schema, a tuple of
    /// several, or <c>z.unknown()</c> when they can't be listed.
    /// </summary>
    private static ZodDeclaration Procedure(IrObject obj, TypeLowering types)
    {
        var summary = obj.Results switch
        {
            null => "its result sets cannot be listed; see the unknowns in the IR",
            [] => "returns no result sets",
            [{ Name: { } name } single] => $"returns one result set, {name}: {IrResultText.Describe(single)}",
            [var single] => $"returns {IrResultText.Describe(single)}",
            var many => $"returns {many.Count} result sets: " + string.Join("; ", many.Select(r => (r.Name is { } name ? name + ": " : "") + IrResultText.Describe(r))),
        };
        var schema = obj.Results switch
        {
            null => Z("unknown"),

            // Strict whatever the objects are: the function builds it from exactly its sets, as JSON Schema's has no other keys.
            var sets when obj.SetNames is { } names => new ObjectSchema([.. sets.Zip(names, (r, name) => new ZodProperty(name, Result(r, types)))], Strict: true),
            [var single] => Result(single, types),
            var many => Z("tuple", new ArrayLiteral([.. many.Select(r => Result(r, types))])),
        };
        return new ZodDeclaration(obj.Name, $"{obj.Id}: {summary}.", schema) { Description = obj.Description };
    }

    /// <summary>
    /// A result's schema. A result that may be absent follows the reader convention in the IR's README: a rowset reads as
    /// <c>[]</c>, so its schema is unchanged, and a JSON result reads as <c>null</c>, whatever its type, because that is
    /// what the mssql driver hands over for a FOR JSON query that matched no rows
    /// (<c>docs/decisions/0048-an-absent-json-result-reads-as-null.md</c>).
    /// </summary>
    private static ZodExpression Result(IrResult result, TypeLowering types)
    {
        var schema = result.Type is IrArray array ? Rows(array, result, types) : types.Type(result.Type, result.Encoding);

        // A rowset reads as no rows when absent, whatever its type (a union of arrays when branches return different rows).
        // An unknown JSON result already accepts null.
        return result.MayBeAbsent && result.Encoding == IrEncoding.Json && result.Type is not IrUnknownType
            ? schema.Then("nullable")
            : schema;
    }

    /// <summary>
    /// A result of rows, a rowset or FOR JSON's array, bounded as the result says it is read (<see cref="IrResult.FewestItems"/>
    /// and <see cref="IrResult.MostItems"/>), each bound written once.
    /// </summary>
    /// <remarks>
    /// Each bound carries its own message, in rows: Zod's counts an array's items ("expected array to have exactly 1 items"),
    /// which is how a result-set failure first read to a team that met one. A FOR JSON array's items are its rows too, one
    /// object each.
    /// </remarks>
    private static ZodExpression Rows(IrArray array, IrResult result, TypeLowering types)
    {
        var schema = types.Type(array with { MinItems = null, MaxItems = null }, result.Encoding);
        if (result.FewestItems is { } exactly && result.MostItems == exactly)
            return schema.Then("length", Count(exactly), Expected("exactly", exactly));
        if (result.FewestItems is { } low)
            schema = schema.Then("min", Count(low), Expected("at least", low));
        return result.MostItems is { } high ? schema.Then("max", Count(high), Expected("at most", high)) : schema;
    }

    private static Number Count(int count) => new(count.ToString(CultureInfo.InvariantCulture));

    /// <summary>A bound's message: "Expected exactly one row", "Expected at most 5 rows", "Expected no rows".</summary>
    private static ObjectLiteral Expected(string how, int count)
    {
        var rows = count switch
        {
            0 => "no rows",
            1 => how + " one row",
            _ => how + " " + count.ToString(CultureInfo.InvariantCulture) + " rows",
        };
        return new ObjectLiteral([new ZodProperty("error", new Text("Expected " + rows))]);
    }
}
