using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;
using Haruspex.Ir;

namespace Haruspex.Emit.Zod;

/// <summary>
/// Emits one TypeScript module from an <see cref="IrDocument"/>: a Zod schema and an inferred type for every
/// named object type and every procedure. It reads only the IR; it knows nothing about SQL.
/// </summary>
/// <remarks>
/// Targets Zod 4 (<c>z.int()</c>, <c>z.guid()</c>, <c>z.iso.*</c>). The output is deterministic, with LF line endings, so it
/// can be committed and checked in CI.
/// </remarks>
public static class ZodEmitter
{
    /// <summary>Emits the module with the default options.</summary>
    /// <exception cref="ZodEmitException">The document cannot be emitted: a name that is not an identifier, or an import that clashes.</exception>
    public static string Emit(IrDocument document) => Emit(document, new ZodOptions());

    /// <summary>Emits the module.</summary>
    /// <exception cref="ZodEmitException">The document cannot be emitted: a name that is not an identifier, or an import that clashes.</exception>
    public static string Emit(IrDocument document, ZodOptions options)
    {
        ArgumentNullException.ThrowIfNull(document);
        ArgumentNullException.ThrowIfNull(options);
        return new Writer(document, options).Write();
    }

    private sealed class Writer(IrDocument document, ZodOptions options)
    {
        private readonly StringBuilder output = new();
        private readonly Dictionary<string, IrEncoding> emitted = new(StringComparer.Ordinal);

        public string Write()
        {
            output.Append("// Generated by haruspex from IR ").Append(IrDocument.CurrentVersion).Append(". Do not edit.\n");
            output.Append("// Rowset results follow the default type mapping of the mssql (tedious) driver.\n");
            output.Append("import { z } from 'zod'\n");
            WriteImports();
            if (UsesContent())
                output.Append(JsonTextHelper);

            foreach (var obj in document.Objects.OrderBy(o => o.Id, StringComparer.Ordinal))
                WriteObject(obj);

            return output.ToString();
        }

        private void WriteObject(IrObject obj)
        {
            RequireIdentifier(obj.Name);
            var summary = obj.Results switch
            {
                null => "its result sets cannot be listed; see the unknowns in the IR",
                [] => "returns no result sets",
                [var single] => $"returns {Describe(single)}",
                var many => $"returns {many.Count} result sets: " + string.Join("; ", many.Select(Describe)),
            };
            var doc = $"/** {Comment(obj.Id)}: {summary}. */\n";

            if (obj.Results is null)
            {
                output.Append('\n').Append(doc);
                WriteSchema(obj.Name, "z.unknown()");
                return;
            }

            foreach (var result in obj.Results)
                WriteDependencies(result.Type, result.Encoding);

            var expression = obj.Results.Count == 1
                ? Result(obj.Results[0])
                : "z.tuple([" + string.Join(", ", obj.Results.Select(Result)) + "])";
            output.Append('\n').Append(doc);
            WriteSchema(obj.Name, expression);
        }

        /// <summary>
        /// A result's schema. A result that may be absent (a FOR JSON query that matched no rows returns no row
        /// at all) follows the reader convention in the IR's README: an array reads as <c>[]</c>, so its schema
        /// is unchanged, and anything else reads as <c>null</c>.
        /// </summary>
        private string Result(IrResult result)
        {
            var code = Expression(result.Type, result.Encoding).Code;

            // A result of rows (a rowset, or FOR JSON's array) has no more rows than its cardinality, and exactly one when it
            // is one and always there. A result that may be absent reads as [] (the reader convention), so it is only bounded
            // above. A union of arrays is not bounded, which only claims less.
            if (result.Type is IrArray)
            {
                code += result.Cardinality switch
                {
                    IrCardinality.One when !result.MayBeAbsent => ".length(1)",
                    IrCardinality.One or IrCardinality.AtMostOne => ".max(1)",
                    _ => "",
                };
            }

            // A rowset reads as no rows when absent, whatever its type (a union of arrays when branches return different rows).
            return result.MayBeAbsent && result.Encoding == IrEncoding.Json && result.Type is not (IrArray or IrUnknownType) ? code + ".nullable()" : code;
        }

        /// <summary>
        /// What a result is, and what it reads as when absent: a FOR JSON query that matched no rows, or a statement that did
        /// not run (in a branch, or after a RETURN), whose result set is then missing altogether.
        /// </summary>
        private static string Describe(IrResult result)
        {
            var noRows = result.AbsentBecause.Any(r => r.Rule == IrNullRules.NoRows);
            var notRun = result.AbsentBecause.Any(r => r.Rule == IrNullRules.NotRun);
            var when = (noRows, notRun) switch
            {
                (true, true) => "when no rows match or it does not run",
                (true, false) => "when no rows match",
                (false, true) => "when it does not run",
                _ => null,
            };
            var what = result.Encoding == IrEncoding.Rowset ? "rows" : "JSON";
            return when is null ? what : $"{what}, {(result.Encoding == IrEncoding.Rowset || result.Type is IrArray ? "[]" : "null")} {when}";
        }

        /// <summary>
        /// JSON text whose content the IR knows: a string that must parse to a value of the content's schema. The type stays
        /// <c>string</c>, since that is what arrives (the consumer parses it); the check only rejects text that does not
        /// hold what the IR claims. The content is a function so that it may name a schema written later, such as a
        /// recursive one.
        /// </summary>
        private const string JsonTextHelper = """

            // JSON text: a string that must parse to a value of its content's schema. Its type stays string.
            const jsonText = (content: () => z.ZodType) =>
              z.string().refine((text) => {
                try {
                  return content().safeParse(JSON.parse(text)).success
                } catch {
                  return false
                }
              }, { error: 'Expected JSON text holding a value of its content type' })

            """;

        /// <summary>
        /// One import per module the config file pointed a value at (<see cref="IrImport"/>), modules and names sorted so
        /// the output is stable. An imported name must not be one this module defines, or two declarations would clash.
        /// </summary>
        private void WriteImports()
        {
            var imports = new SortedDictionary<string, SortedSet<string>>(StringComparer.Ordinal);
            var modules = new Dictionary<string, string>(StringComparer.Ordinal);
            foreach (var import in AllTypes().SelectMany(Imports))
            {
                if (!IrIdentifiers.IsIdentifier(import.Name) || IrIdentifiers.IsReserved(import.Name))
                    throw new ZodEmitException($"The imported name '{import.Name}' is not a valid TypeScript identifier.");
                if (modules.TryGetValue(import.Name, out var other) && other != import.From)
                    throw new ZodEmitException($"'{import.Name}' is imported from both '{other}' and '{import.From}'.");
                modules[import.Name] = import.From;
                if (!imports.TryGetValue(import.From, out var names))
                    imports[import.From] = names = new SortedSet<string>(StringComparer.Ordinal);
                names.Add(import.Name);
            }

            var defined = document.Objects.Select(o => o.Name).Concat(document.Types.Keys)
                .SelectMany(n => new[] { n, n + "Schema" }).Append("z").Append("jsonText").ToHashSet(StringComparer.Ordinal);
            foreach (var name in modules.Keys.Where(defined.Contains).Order(StringComparer.Ordinal))
                throw new ZodEmitException($"The imported name '{name}' is also a name this module defines or uses.");

            foreach (var (from, names) in imports)
            {
                output.Append("import { ").Append(string.Join(", ", names)).Append(" } from ")
                    .Append(Quote(from)).Append('\n');
            }
        }

        private IEnumerable<IrType> AllTypes() =>
            document.Types.Values.SelectMany(t => t.Fields.Select(f => f.Type))
                .Concat(document.Objects.SelectMany(o => o.Results ?? []).Select(r => r.Type));

        private static IEnumerable<IrImport> Imports(IrType type) => type switch
        {
            IrImport import => [import],
            IrArray array => Imports(array.Items),
            IrTuple tuple => tuple.Items.SelectMany(e => Imports(e.Type)),
            IrRecord record => Imports(record.Values),
            IrUnion union => union.Variants.SelectMany(Imports),
            IrJsonText { Content: { } content } => Imports(content),
            _ => [],
        };

        private static string Quote(string text) =>
            "'" + JsonEncodedText.Encode(text, JavaScriptEncoder.UnsafeRelaxedJsonEscaping).ToString().Replace("'", "\\'", StringComparison.Ordinal) + "'";

        /// <summary>Whether any type in the document is JSON text with content, so the helper is written only when used.</summary>
        private bool UsesContent()
        {
            static bool Has(IrType type) => type switch
            {
                IrJsonText { Content: not null } => true,
                IrArray array => Has(array.Items),
                IrTuple tuple => tuple.Items.Any(e => Has(e.Type)),
                IrRecord record => Has(record.Values),
                IrUnion union => union.Variants.Any(Has),
                _ => false,
            };

            return document.Types.Values.Any(t => t.Fields.Any(f => Has(f.Type)))
                || document.Objects.Any(o => o.Results?.Any(r => Has(r.Type)) == true);
        }

        /// <summary>Writes every named type reachable from <paramref name="type"/>, each before its users.</summary>
        private void WriteDependencies(IrType type, IrEncoding encoding)
        {
            switch (type)
            {
                case IrArray array:
                    WriteDependencies(array.Items, encoding);
                    break;
                case IrTuple tuple:
                    foreach (var element in tuple.Items)
                        WriteDependencies(element.Type, encoding);
                    break;
                case IrRecord record:
                    WriteDependencies(record.Values, encoding);
                    break;
                case IrJsonText { Content: { } content }:
                    // What the text holds is JSON, even in a rowset.
                    WriteDependencies(content, IrEncoding.Json);
                    break;
                case IrUnion union:
                    foreach (var variant in union.Variants)
                        WriteDependencies(variant, encoding);
                    break;
                case IrRef reference:
                    if (emitted.TryGetValue(reference.Name, out var previous))
                    {
                        // Scalars map differently by encoding (a date is a string in JSON, a Date in a row), so a
                        // type shared between encodings would need two schemas. The IR never shares them today.
                        if (previous != encoding)
                            throw new InvalidOperationException($"The type {reference.Name} is used in both a rowset and a JSON result.");
                        break;
                    }

                    RequireIdentifier(reference.Name);
                    emitted[reference.Name] = encoding;
                    var objectType = document.Types[reference.Name];
                    foreach (var field in objectType.Fields)
                        WriteDependencies(field.Type, encoding);

                    // Strip by default: unknown keys are dropped at parse time, so a column the database adds before the
                    // application redeploys doesn't break it. Strict is a setting for projects that deploy the
                    // application first or together, and want an unexpected key to fail. Decided 9 Nov 2026: strict was
                    // the first default, reversed because the common order, database first, would make strict break every
                    // running application whenever a column is added. Every object here is part of a result.
                    var body = new StringBuilder(options.Objects == ZodObjects.Strict ? "z.strictObject({\n" : "z.object({\n");
                    foreach (var field in objectType.Fields)
                    {
                        // A field that refers back into its own cycle (a tree's children) is a getter, Zod 4's form for
                        // recursive objects: the schema it names may not be defined yet, and TypeScript infers the type
                        // through a getter without casts. Every such reference is one, whichever type is written first.
                        if (Refs(field.Type).Any(r => Reaches(r, reference.Name)))
                            body.Append("  get ").Append(Key(field.Name)).Append("() { return ").Append(Field(field, encoding)).Append(" },\n");
                        else
                            body.Append("  ").Append(Key(field.Name)).Append(": ").Append(Field(field, encoding)).Append(",\n");
                    }

                    body.Append("})");

                    output.Append('\n');
                    WriteSchema(reference.Name, body.ToString());
                    break;
            }
        }

        /// <summary>The named types a type refers to directly, through arrays, tuples, records and unions.</summary>
        private static IEnumerable<string> Refs(IrType type) => type switch
        {
            IrRef reference => [reference.Name],
            IrArray array => Refs(array.Items),
            IrTuple tuple => tuple.Items.SelectMany(e => Refs(e.Type)),
            IrRecord record => Refs(record.Values),
            IrUnion union => union.Variants.SelectMany(Refs),
            IrJsonText { Content: { } content } => Refs(content),
            _ => [],
        };

        /// <summary>Whether <paramref name="from"/> refers to <paramref name="to"/>, itself or through other types.</summary>
        private bool Reaches(string from, string to)
        {
            var seen = new HashSet<string>(StringComparer.Ordinal);
            var queue = new Queue<string>([from]);
            while (queue.TryDequeue(out var next))
            {
                if (next == to)
                    return true;
                if (!seen.Add(next))
                    continue;
                foreach (var field in document.Types[next].Fields)
                {
                    foreach (var further in Refs(field.Type))
                        queue.Enqueue(further);
                }
            }

            return false;
        }

        private void WriteSchema(string name, string expression) =>
            output.Append("export const ").Append(name).Append("Schema = ").Append(expression).Append('\n')
                .Append("export type ").Append(name).Append(" = z.infer<typeof ").Append(name).Append("Schema>\n");

        /// <summary>
        /// A field's schema. Presence and nullability are separate: a key that is left out when null is
        /// <c>.optional()</c> (never null), and a key that is kept as null is <c>.nullable()</c> (never absent).
        /// </summary>
        private string Field(IrField field, IrEncoding encoding)
        {
            var (code, comment) = Expression(field.Type, encoding);
            if (field.Nullable && field.Presence == IrPresence.OmittedWhenNull)
                code += ".optional()";
            else if (field.Nullable && field.Type is not IrUnknownType) // z.unknown() already accepts null
                code += ".nullable()";
            return comment is null ? code : $"{code} /* {Comment(comment)} */";
        }

        private (string Code, string? Comment) Expression(IrType type, IrEncoding encoding) => type switch
        {
            IrScalar scalar => Scalar(scalar, encoding),
            IrArray array => Array(array, encoding),
            IrTuple tuple => Combine("z.tuple([", tuple.Items.Select(e => Nullable(Expression(e.Type, encoding), e.Nullable, e.Type)), "])"),
            IrRecord record => Combine("z.record(z.string(), ", [Nullable(Expression(record.Values, encoding), record.ValuesNullable, record.Values)], ")"),
            IrUnion union => Union(union, encoding),
            IrRef reference => ($"{reference.Name}Schema", null),
            IrImport import => (import.Name, null),
            IrJsonText { Content: { } content } => JsonText(Expression(content, IrEncoding.Json)),
            IrJsonText => ("z.string()", "JSON text"),
            IrUnknownType unknown => ("z.unknown()", unknown.Reason),
            _ => throw new ArgumentOutOfRangeException(nameof(type), type, "Unknown IR type node."),
        };

        /// <summary>
        /// A union. <c>z.union</c> returns the first variant that accepts a value, and a <c>z.object</c> strips the keys it
        /// doesn't know, so a variant would accept another's object and drop its keys: a key left out when null is
        /// <c>.optional()</c>, so even a variant with more keys accepts an object of fewer, and no order prevents it. So each
        /// object variant (or array of one) also rejects every key that only the other variants have,
        /// <c>.extend({ k: z.never().optional() })</c>: an object takes the variant whose keys it has, and keeps them all.
        /// Keys no variant knows are still stripped (or refused, for strict objects), as everywhere else.
        /// </summary>
        private (string Code, string? Comment) Union(IrUnion union, IrEncoding encoding)
        {
            var keys = union.Variants.Select(ObjectKeys).ToList();
            var parts = SupersetsFirst(union.Variants).Select(variant =>
            {
                var index = union.Variants.ToList().IndexOf(variant);
                var mine = keys[index];
                var others = keys.Where((k, i) => i != index && k is not null).SelectMany(k => k!)
                    .Where(k => mine is not null && !mine.Contains(k, StringComparer.Ordinal))
                    .Distinct(StringComparer.Ordinal).ToList();
                if (others.Count == 0)
                    return Expression(variant, encoding);
                var never = ".extend({ " + string.Join(", ", others.Select(k => $"{Key(k)}: z.never().optional()")) + " })";
                return variant switch
                {
                    IrRef reference => ($"{reference.Name}Schema{never}", null),
                    IrArray { Items: IrRef item } => ($"z.array({item.Name}Schema{never})", null),
                    _ => Expression(variant, encoding),
                };
            });
            return Combine("z.union([", parts, "])");
        }

        /// <summary>The keys of a variant that is an object, or a plain array of one; null for any other.</summary>
        private List<string>? ObjectKeys(IrType type) => type switch
        {
            IrRef reference when document.Types.TryGetValue(reference.Name, out var target) => [.. target.Fields.Select(f => f.Name)],
            IrArray { Items: IrRef reference, MinItems: null, MaxItems: null, ItemsNullable: false } => ObjectKeys(reference),
            _ => null,
        };

        /// <summary>
        /// A union's variants with those of more keys first. <c>z.union</c> returns the first variant that accepts a value,
        /// and a <c>z.object</c> strips the keys it doesn't know, so an object variant whose keys are a subset of another's
        /// would accept the other's values and drop their extra keys. A rowset's columns are always all there, so a row only
        /// fits a variant whose keys it has, and putting more keys first makes the one it takes its own. An array of objects
        /// is ordered by its objects. Equal counts keep the IR's order.
        /// </summary>
        private IEnumerable<IrType> SupersetsFirst(IReadOnlyList<IrType> variants) =>
            variants.Select((v, i) => (Variant: v, Index: i))
                .OrderByDescending(x => Keys(x.Variant))
                .ThenBy(x => x.Index)
                .Select(x => x.Variant);

        private int Keys(IrType type) => type switch
        {
            IrRef reference when document.Types.TryGetValue(reference.Name, out var target) => target.Fields.Count,
            IrArray array => Keys(array.Items),
            _ => 0,
        };

        private static (string Code, string? Comment) JsonText((string Code, string? Comment) content) =>
            ($"jsonText(() => {content.Code})", content.Comment is null ? "JSON text" : $"JSON text; {content.Comment}");

        /// <summary>
        /// An array, with its items' nullability and its length when the IR knows them (<c>json_array</c> and the
        /// aggregates; an array FOR JSON builds has neither).
        /// </summary>
        private (string Code, string? Comment) Array(IrArray array, IrEncoding encoding)
        {
            var (code, comment) = Combine("z.array(", [Nullable(Expression(array.Items, encoding), array.ItemsNullable, array.Items)], ")");
            if (array.MinItems is { } min)
                code += $".min({min.ToString(System.Globalization.CultureInfo.InvariantCulture)})";
            if (array.MaxItems is { } max)
                code += $".max({max.ToString(System.Globalization.CultureInfo.InvariantCulture)})";
            return (code, comment);
        }

        /// <summary>A value that may be null; <c>z.unknown()</c> already accepts null.</summary>
        private static (string Code, string? Comment) Nullable((string Code, string? Comment) value, bool nullable, IrType type) =>
            nullable && type is not IrUnknownType ? (value.Code + ".nullable()", value.Comment) : value;

        /// <summary>Parts joined into one expression, with their comments joined once each.</summary>
        private static (string Code, string? Comment) Combine(string open, IEnumerable<(string Code, string? Comment)> parts, string close)
        {
            var list = parts.ToList();
            var comments = list.Select(p => p.Comment).OfType<string>().Distinct(StringComparer.Ordinal).ToList();
            return (open + string.Join(", ", list.Select(p => p.Code)) + close, comments.Count == 0 ? null : string.Join("; ", comments));
        }

        /// <summary>
        /// A scalar as the caller receives it.
        /// </summary>
        /// <remarks>
        /// <para>
        /// In JSON, SQL Server writes every number as a JSON number, and dates, times and uniqueidentifiers as
        /// strings in a fixed format, so those are validated strings. They are deliberately not converted to
        /// <c>Date</c>: a <c>date</c> or an offset-less <c>datetime2</c> has no time zone, and
        /// <c>new Date('2026-11-09')</c> is UTC midnight, which shows as the previous day west of Greenwich.
        /// Conversion could become an emitter option later. Fractional-second precision is not constrained.
        /// The differential tests pinned what FOR JSON writes (the IR's README, "Scalars in JSON"): a fraction
        /// of exactly the type's scale, left out when zero, and a zero offset as <c>Z</c>. These validators accept
        /// every such string (checked against zod 4.6.7). A uniqueidentifier is <c>z.guid()</c>, not
        /// <c>z.uuid()</c>, because its value need not be an RFC 9562 UUID.
        /// </para>
        /// <para>
        /// In a rowset, the mssql driver returns dates and times as <c>Date</c> and <c>bigint</c> as a string,
        /// because a JavaScript number cannot hold every 64-bit value.
        /// </para>
        /// </remarks>
        private static (string Code, string? Comment) Scalar(IrScalar scalar, IrEncoding encoding)
        {
            var json = encoding == IrEncoding.Json;
            return scalar.Kind switch
            {
                IrScalarKind.String => Facets.String(scalar),
                IrScalarKind.Boolean => ("z.boolean()", null),
                IrScalarKind.Uuid => ("z.guid()", null),
                IrScalarKind.Date => (json ? "z.iso.date()" : "z.date()", null),
                IrScalarKind.Time => (json ? "z.iso.time()" : "z.date()", null),
                IrScalarKind.Datetime when !json => ("z.date()", null),
                IrScalarKind.Datetime => scalar.Format switch
                {
                    IrFormats.Local => ("z.iso.datetime({ local: true })", null),
                    IrFormats.Offset => ("z.iso.datetime({ offset: true })", null),
                    // Without a format the offset is not known, so no format is claimed.
                    _ => ("z.string()", null),
                },
                IrScalarKind.Number => Facets.Number(scalar, json),
                _ => throw new ArgumentOutOfRangeException(nameof(scalar), scalar.Kind, "Unknown scalar kind."),
            };
        }

        /// <summary>
        /// Text made safe inside a comment. Names come from the IR, which comes from SQL where a bracketed
        /// identifier may hold anything, so a <c>*/</c> or a line break must not end the comment early.
        /// </summary>
        private static string Comment(string text) =>
            text.Replace("*/", "*\\/", StringComparison.Ordinal)
                .Replace("\r", " ", StringComparison.Ordinal)
                .Replace("\n", " ", StringComparison.Ordinal)
                .Replace("\u2028", " ", StringComparison.Ordinal)
                .Replace("\u2029", " ", StringComparison.Ordinal);

        /// <summary>
        /// Names become TypeScript identifiers. The front end only settles valid ones, but the IR is a file
        /// that anything can write, so a name that would not be an identifier is refused rather than emitted.
        /// </summary>
        private static void RequireIdentifier(string name)
        {
            if (!IrIdentifiers.IsIdentifier(name) || IrIdentifiers.IsReserved(name))
                throw new ZodEmitException($"The IR name '{name}' is not a valid TypeScript identifier.");
        }

        private static string Key(string name) =>
            IrIdentifiers.IsIdentifier(name) ? name : "\"" + JsonEncodedText.Encode(name, JavaScriptEncoder.UnsafeRelaxedJsonEscaping) + "\"";
    }
}
